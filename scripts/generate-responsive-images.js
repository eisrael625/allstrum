#!/usr/bin/env node
/**
 * Generates responsive WebP variants for the site's photos plus an
 * importable manifest (src/assets/resized/index.js) with src/srcSet pairs.
 *
 * Usage: node scripts/generate-responsive-images.js
 * Re-run after adding an entry to IMAGES below, then commit the output.
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'src', 'assets', 'resized');
const WIDTHS = [480, 960, 1600];
const QUALITY = 78;

// key → source file (relative to repo root)
const IMAGES = {
  'gallery-3710': 'src/assets/gallery-3710.webp',
  'gallery-4269': 'src/assets/gallery-4269.webp',
  'gallery-4276': 'src/assets/gallery-4276.webp',
  'gallery-4263': 'src/assets/gallery-4263.webp',
  'gallery-4237': 'src/assets/gallery-4237.webp',
  'gallery-4134': 'src/assets/gallery-4134.webp',
  'gallery-3238': 'src/assets/gallery-3238.webp',
  'gallery-3230': 'src/assets/gallery-3230.webp',
  'gallery-4038': 'src/assets/gallery-4038.webp',
  'gallery-4042': 'src/assets/gallery-4042.webp',
  'gallery-3971': 'src/assets/gallery-3971.webp',
  'gallery-3701': 'src/assets/gallery-3701.webp',
  'gallery-4050': 'src/assets/gallery-4050.webp',
  'gallery-4051': 'src/assets/gallery-4051.webp',
  'gallery-4052': 'src/assets/gallery-4052.webp',
  'gallery-4055': 'src/assets/gallery-4055.webp',
  'as1-gallery': 'src/assets/AS1-gallery.webp',
  'as2-gallery': 'src/assets/AS2-gallery.webp',
  'as3-gallery': 'src/assets/AS3-gallery.webp',
  'as4-gallery': 'src/assets/AS4-gallery.webp',
  'as1': 'src/assets/as1.webp',
  'camp': 'src/camp.webp',
  'ukulele-pic': 'src/ukulele-pic.webp',
  'guitar-casual': 'src/assets/guitar-casual.webp',
  'kids-music': 'src/assets/kids-music.webp',
  'returninplayers': 'src/assets/returninplayers.jpg',
};

const toIdent = (key) =>
  key.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/[^a-zA-Z0-9]/g, '');

(async () => {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const imports = [];
  const entries = [];

  for (const [key, rel] of Object.entries(IMAGES)) {
    const srcPath = path.join(ROOT, rel);
    const meta = await sharp(srcPath).metadata();
    const widths = WIDTHS.filter((w) => w < meta.width);
    if (!widths.length || meta.width <= Math.min(...WIDTHS)) widths.push(meta.width);
    else if (meta.width < Math.max(...WIDTHS)) widths.push(meta.width);

    const variants = [];
    for (const w of widths) {
      const file = `${key}-w${w}.webp`;
      await sharp(srcPath)
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: QUALITY })
        .toFile(path.join(OUT_DIR, file));
      const ident = `${toIdent(key)}W${w}`;
      imports.push(`import ${ident} from './${file}';`);
      variants.push({ ident, w });
    }

    const fallback = variants.reduce((best, v) =>
      Math.abs(v.w - 960) < Math.abs(best.w - 960) ? v : best
    );
    entries.push(
      `  '${key}': {\n` +
      `    src: ${fallback.ident},\n` +
      `    srcSet: [${variants.map((v) => `\`\${${v.ident}} ${v.w}w\``).join(', ')}].join(', '),\n` +
      `  },`
    );
    console.log(`${key}: ${widths.join(', ')}w`);
  }

  const manifest =
    '// AUTO-GENERATED by scripts/generate-responsive-images.js — do not edit by hand.\n' +
    `${imports.join('\n')}\n\n` +
    `const responsiveImages = {\n${entries.join('\n')}\n};\n\n` +
    'export default responsiveImages;\n';

  fs.writeFileSync(path.join(OUT_DIR, 'index.js'), manifest);
  console.log(`\nWrote ${Object.keys(IMAGES).length} image sets to src/assets/resized/`);
})();
